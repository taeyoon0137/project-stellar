#!/usr/bin/env python3
"""터미널 셀 폭 표 생성기 (XVIII.4.1).

`crates/terminal/src/vt/width_table.rs`를 만듭니다. 표는 Python 표준 라이브러리 `unicodedata`의
Unicode 데이터베이스에서 계산하며, 생성 파일 머리에 그 Unicode 버전을 기록합니다.

규칙(셀 폭):
- 0: general category Mn·Me(결합 부호), Cf(서식 문자, 단 U+00AD soft hyphen과 U+0600~U+0605·
  U+06DD·U+070F·U+0890~U+0891·U+08E2·U+110BD·U+110CD 같은 prepended concatenation mark 제외),
  Hangul 중성·종성 자모(U+1160~U+11FF, U+D7B0~U+D7FF), emoji skin tone modifier(U+1F3FB~U+1F3FF).
- 2: East Asian Width가 W 또는 F인 문자(위 0 규칙에 걸리지 않는 것).
- 그 밖은 1(East Asian Width A·N·Na·H 포함).

사용법(저장소 루트에서):
    python3 crates/terminal/tools/gen_width.py > crates/terminal/src/vt/width_table.rs
"""

import sys
import unicodedata

PREPENDED = set(range(0x0600, 0x0606)) | {0x06DD, 0x070F, 0x0890, 0x0891, 0x08E2, 0x110BD, 0x110CD}


def width(cp: int) -> int:
    ch = chr(cp)
    cat = unicodedata.category(ch)
    if 0x1160 <= cp <= 0x11FF or 0xD7B0 <= cp <= 0xD7FF or 0x1F3FB <= cp <= 0x1F3FF:
        return 0
    if cat in ("Mn", "Me"):
        return 0
    if cat == "Cf" and cp != 0x00AD and cp not in PREPENDED:
        return 0
    if cat in ("Cs", "Cc"):
        # 제어 문자와 surrogate는 print 경로에 오지 않습니다. 표에는 1로 둡니다.
        return 1
    if unicodedata.east_asian_width(ch) in ("W", "F"):
        return 2
    return 1


def ranges(target: int):
    out = []
    start = None
    for cp in range(0x0300, 0x110000):
        hit = width(cp) == target
        if hit and start is None:
            start = cp
        elif not hit and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def emit(name: str, items, doc: str):
    print(f"/// {doc}")
    print(f"pub(super) const {name}: &[(u32, u32)] = &[")
    for lo, hi in items:
        print(f"    (0x{lo:04X}, 0x{hi:04X}),")
    print("];")


def main():
    # U+0300 미만에는 폭 0·2 문자가 없습니다(제어 문자 제외). 생성기가 이를 확인합니다.
    for cp in range(0x20, 0x300):
        if cp == 0x7F or 0x80 <= cp < 0xA0:
            continue
        assert width(cp) == 1 or cp == 0x00AD, hex(cp)
    print("// @generated by crates/terminal/tools/gen_width.py — 직접 수정하지 않습니다.")
    print(f"// Unicode {unicodedata.unidata_version} (Python {sys.version.split()[0]} unicodedata).")
    print()
    print(f"/// 표를 만든 Unicode 버전.")
    print(f'pub(super) const UNICODE_VERSION: &str = "{unicodedata.unidata_version}";')
    print()
    emit("ZERO_WIDTH", ranges(0), "셀 폭 0 범위(포함 구간, 오름차순).")
    print()
    emit("DOUBLE_WIDTH", ranges(2), "셀 폭 2 범위(포함 구간, 오름차순).")


if __name__ == "__main__":
    main()
